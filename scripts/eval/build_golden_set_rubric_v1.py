    mis = json.loads(MISCONCEPTIONS.read_text(encoding="utf-8"))["misconceptions"]
    mis_by_id = {m["mis_id"]: m for m in mis}

    out_nodes: list[dict] = []
    n_prop = 0
    for n in NODES:
        std = by_code_2022.get(n["standard_code"])
        if std is None:
            print(
                f"!! 2022 개정 성취기준 없음: {n['golden_id']} {n['standard_code']}",
                file=sys.stderr,
            )
            return 1
        # M-id 실재 검증(날조 차단) — 설명이 다루는 오개념 + 선지에 걸린 오개념 전부
        refs = list(n["misconception_ids_addressed"]) + [
            r["misconception_id"] for r in n["mc_item"]["distractor_map"] if "misconception_id" in r
        ]
        missing = [r for r in refs if r not in mis_by_id]
        if missing:
            print(f"!! DB에 없는 M-id: {n['golden_id']} {missing}", file=sys.stderr)
            return 1
        n_prop += sum(1 for r in n["mc_item"]["distractor_map"] if "misconception_proposal" in r)
