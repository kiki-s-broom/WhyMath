CATS = {"clarification", "assumption", "evidence", "perspective", "implication", "meta"}
POLYA = {"이해", "계획", "실행", "반성"}


def turn(n: int, tutor: str, cat: str, hint: int, stage: str, student: str) -> dict:
    """소크라테스 1턴 — 질문 1개·3문장 이내는 생성 후 채점기가 다시 검사한다."""
    assert cat in CATS and stage in POLYA and 1 <= hint <= 4
    return {
        "turn": n,
        "tutor": tutor,
        "socratic_category": cat,
        "hint_level": hint,
        "polya_stage": stage,
        "expected_student": student,
    }


def d(idx: int, op: str, mis: str | None, derivation: str, proposal: dict | None = None) -> dict:
    """오답 선지 1개의 추적 정보 — OP_00이 아니면 M-id 또는 신설 제안 블록이 반드시 있어야 한다."""
    row: dict = {"choice_index": idx, "op_code": op, "derivation": derivation}
    if op != "OP_00":
        assert (mis is not None) != (
            proposal is not None
        ), f"선지 {idx}: M-id와 제안 중 정확히 하나"
    if mis:
        row["misconception_id"] = mis
    if proposal:
        row["misconception_proposal"] = {"review_status": "pending", **proposal}
    return row


def prop(pid: str, code: str, etype: str, canon: str, thinking: str) -> dict:
    """DB에 없는 오개념의 신설 제안 블록(검수 큐 등재용·misconceptions_v1 필드명 그대로)."""
    return {
        "proposal_id": pid,
        "standard_code": code,
        "error_type": etype,
        "canonical_statement": canon,
        "student_wrong_thinking": thinking,
    }


